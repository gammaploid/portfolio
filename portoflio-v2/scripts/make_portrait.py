"""Build public/js/portrait-data.js, the tone grid the hero turns into a field of digits.

Each cell of a 160 x 200 grid becomes one base64 character: A is outside the subject
(mask from macOS Vision, scripts/mask.swift); otherwise 1 + tone * 2 + red, with tone in
0..30 and red marking shemagh threads. Shipping the grid as script, not an image, keeps
the portrait working when the page is opened straight from disk.

    python3 scripts/make_portrait.py ~/Pictures/hassan.jpeg
"""
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter, ImageOps

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'public' / 'js' / 'portrait-data.js'
BOX = (230, 250, 1460, 1790)  # head and shoulders in the 1684 x 2528 original
GRID = (160, 200)
B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'


def main(photo):
    src = ImageOps.exif_transpose(Image.open(photo)).convert('RGB')
    with tempfile.TemporaryDirectory() as tmp:
        flat, mask_path = Path(tmp) / 'src.png', Path(tmp) / 'mask.png'
        src.save(flat)
        subprocess.run(['swift', str(HERE / 'mask.swift'), str(flat), str(mask_path)], check=True)
        mask = Image.open(mask_path).convert('L').resize(src.size)

    src, mask = src.crop(BOX), mask.crop(BOX)

    tone = ImageOps.grayscale(src)
    # Broad, middle and fine local contrast, so brows and eyes survive as digits.
    for radius, percent in ((40, 70), (10, 80), (3, 170)):
        tone = tone.filter(ImageFilter.UnsharpMask(radius=radius, percent=percent, threshold=1))

    rgb = np.asarray(src).astype(float) / 255
    red = (rgb[..., 0] - np.maximum(rgb[..., 1], rgb[..., 2])) > 0.28
    red = Image.fromarray((red * 255).astype(np.uint8))

    tone, red, mask = (np.asarray(im.resize(GRID, Image.BOX)).astype(float) / 255 for im in (tone, red, mask))
    codes = []
    for t, r, m in zip(tone.ravel(), red.ravel(), mask.ravel()):
        codes.append(B64[1 + round(t * 30) * 2 + int(r > 0.35)] if m >= 0.5 else 'A')

    OUT.write_text(
        '// Generated by scripts/make_portrait.py from a photo of Hassan. Do not edit by hand.\n'
        f"window.HASSAN_PORTRAIT = {{ w: {GRID[0]}, h: {GRID[1]}, data: '{''.join(codes)}' }};\n"
    )
    print(f'wrote {OUT}, {OUT.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path.home() / 'Pictures' / 'hassan.jpeg'))
